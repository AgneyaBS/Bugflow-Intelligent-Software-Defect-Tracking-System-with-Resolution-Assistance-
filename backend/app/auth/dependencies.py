def require_admin(
    current_user: User = Depends(get_current_user)
):
    """
    Allow access only to users with the ADMIN role.
    """

    if current_user.role != "ADMIN":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Admin access required"
        )

    return current_user